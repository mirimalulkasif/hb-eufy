import { spawn, type ChildProcessWithoutNullStreams } from 'node:child_process';
import { createServer, type Socket } from 'node:net';
import { Readable } from 'node:stream';
import { existsSync } from 'node:fs';

import ffmpegStatic from 'ffmpeg-for-homebridge';
import { pickPort } from 'pick-port';

export function resolveFfmpegPath(override?: string): string {
  if (override && existsSync(override)) {
    return override;
  }
  if (typeof ffmpegStatic === 'string' && ffmpegStatic && existsSync(ffmpegStatic)) {
    return ffmpegStatic;
  }
  return 'ffmpeg';
}

/** Serve a Readable once over a local TCP port for ffmpeg `-i tcp://...`. */
export async function serveReadableOnce(input: Readable): Promise<number> {
  const port = await pickPort({ type: 'tcp', ip: '127.0.0.1', reserveTimeout: 15 });
  await new Promise<void>((resolve, reject) => {
    const server = createServer((socket: Socket) => {
      server.close();
      socket.on('drain', () => input.resume());
      input.on('data', (chunk: Buffer) => {
        if (!socket.write(chunk)) {
          input.pause();
        }
      });
      input.on('end', () => socket.end());
      input.on('error', () => socket.destroy());
      socket.on('error', () => {
        if (!input.destroyed) {
          input.destroy();
        }
      });
      socket.on('close', () => {
        if (!input.destroyed) {
          input.destroy();
        }
      });
    });
    server.once('error', reject);
    server.listen(port, '127.0.0.1', () => resolve());
    setTimeout(() => {
      try {
        server.close();
      } catch {
        // ignore
      }
    }, 30_000);
  });
  return port;
}

export type FfmpegHandle = {
  process: ChildProcessWithoutNullStreams;
  stop: () => void;
};

export function startFfmpeg(
  ffmpegPath: string,
  args: string[],
  onStarted: () => void,
  onError: (err: Error) => void,
): FfmpegHandle {
  const process = spawn(ffmpegPath, args, { env: processEnv() });
  let started = false;

  const markStarted = () => {
    if (!started) {
      started = true;
      onStarted();
    }
  };

  process.stderr.on('data', (data: Buffer) => {
    const text = data.toString();
    if (!started && (text.includes('frame=') || text.includes('bitrate=') || text.includes('Stream #'))) {
      markStarted();
    }
  });

  process.on('error', (err) => onError(err));
  process.on('exit', (code, signal) => {
    if (!started) {
      onError(new Error(`ffmpeg exited before start (code=${code}, signal=${signal})`));
    }
  });

  // Fallback: if stderr never reports progress, still unblock HomeKit after a short delay.
  setTimeout(() => markStarted(), 2500);

  return {
    process,
    stop: () => {
      try {
        process.kill('SIGTERM');
      } catch {
        // ignore
      }
      setTimeout(() => {
        try {
          process.kill('SIGKILL');
        } catch {
          // ignore
        }
      }, 2000);
    },
  };
}

function processEnv(): NodeJS.ProcessEnv {
  return { ...process.env };
}

export async function grabJpegFromStream(
  ffmpegPath: string,
  video: Readable,
  width: number,
  height: number,
): Promise<Buffer> {
  const port = await serveReadableOnce(video);
  return new Promise<Buffer>((resolve, reject) => {
    const args = [
      '-hide_banner',
      '-loglevel',
      'error',
      '-f',
      'h264',
      '-i',
      `tcp://127.0.0.1:${port}`,
      '-frames:v',
      '1',
      '-vf',
      `scale=${width}:${height}:force_original_aspect_ratio=decrease`,
      '-f',
      'image2',
      'pipe:1',
    ];
    const child = spawn(ffmpegPath, args, { env: processEnv() });
    const chunks: Buffer[] = [];
    const timer = setTimeout(() => {
      child.kill('SIGKILL');
      reject(new Error('snapshot timeout'));
    }, 12_000);
    child.stdout.on('data', (c: Buffer) => chunks.push(c));
    child.on('error', (err) => {
      clearTimeout(timer);
      reject(err);
    });
    child.on('close', (code) => {
      clearTimeout(timer);
      if (code === 0 && chunks.length) {
        resolve(Buffer.concat(chunks));
      } else {
        reject(new Error(`snapshot ffmpeg exited ${code}`));
      }
    });
  });
}

